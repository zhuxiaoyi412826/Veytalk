-- -------------------------------------------------------------------------------------
-- 0. 预检（只读，不动数据）。三条都看完再决定要不要往下跑。
--
--    0.1 两张新表在不在：都应当报 0（存在即已建过，第 1 段的 IF NOT EXISTS 会跳过）。
