    ON m.session_id = e.session_id AND m.role = 'user' AND m.turn_no = e.turn_no - 1
SET e.detail = CONCAT('answerChars=', m.char_count)
WHERE e.event_type = 'turn-submit'
  AND e.id BETWEEN 9300 AND 9399;

