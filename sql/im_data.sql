-- 跑完本文件后必须清一次 im:auth:* 权限缓存，否则已登录的管理员在 TTL 内仍看不到这一点。
-- 119~122 是后台四期第五批的四屏（钱包与礼物 / AI 面试记录 / 群组管理 / 消息管理）。
-- ★ 这一批零 DDL：四屏读的全是早已存在的表（im_user_wallet / im_gift / im_gift_record /
